def seed_database_if_empty(db):
    """Seed initial pages if database contains zero pages."""
    if db.get_total_pages() == 0:
        for page in SEED_PAGES:
            db.add_or_update_page(
                url=page["url"],
                domain=page["domain"],
                title=page["title"],
                description=page["description"],
                raw_body=page["raw_body"]
            )
